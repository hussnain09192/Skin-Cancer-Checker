"""### 1. Data Preparation using ImageDataGenerator
We will set up training and testing image generators. Since the data directory has structured subfolders (`data/train` and `data/test`), we can utilize Keras' `ImageDataGenerator` to load, resize, scale, and batch the image files automatically.
"""

import tensorflow as tf
from tensorflow.keras.preprocessing.image import ImageDataGenerator

# Define paths and parameters
base_dir = os.path.join(extract_path, 'data')
train_dir = os.path.join(base_dir, 'train')
test_dir = os.path.join(base_dir, 'test')

BATCH_SIZE = 32
IMG_SIZE = (128, 128)

# Rescale pixel values from [0, 255] to [0, 1]
train_datagen = ImageDataGenerator(
    rescale=1./255,
    rotation_range=20,
    width_shift_range=0.2,
    height_shift_range=0.2,
    horizontal_flip=True,
    validation_split=0.2 # Use 20% of training data for validation
)

test_datagen = ImageDataGenerator(rescale=1./255)

# Create data generators
train_generator = train_datagen.flow_from_directory(
    train_dir,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='binary',
    subset='training'
)

val_generator = train_datagen.flow_from_directory(
    train_dir,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='binary',
    subset='validation'
)

test_generator = test_datagen.flow_from_directory(
    test_dir,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='binary',
    shuffle=False
)

# Inspect class indices mapping
print("Class Indices:", train_generator.class_indices)

"""### 2. Building the Convolutional Neural Network (CNN)
We construct a simple sequential CNN model consisting of Conv2D layers for feature extraction, MaxPooling2D for downsampling, and Dense layers for classification.
"""

from tensorflow.keras import layers, models

model = models.Sequential([
    # First Convolutional block
    layers.Conv2D(32, (3, 3), activation='relu', input_shape=(128, 128, 3)),
    layers.MaxPooling2D((2, 2)),

    # Second Convolutional block
    layers.Conv2D(64, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    # Third Convolutional block
    layers.Conv2D(128, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    # Flattening and Dense Layers
    layers.Flatten(),
    layers.Dense(128, activation='relu'),
    layers.Dropout(0.5), # Regularization
    layers.Dense(1, activation='sigmoid') # Binary output (e.g., benign vs malignant)
])

# Compile the model
model.compile(
    optimizer='adam',
    loss='binary_crossentropy',
    metrics=['accuracy']
)

model.summary()

"""### 3. Model Training & Evaluation
We will train the CNN model on the generator datasets and then evaluate its final performance on the test set.
"""

epochs = 10

history = model.fit(
    train_generator,
    validation_data=val_generator,
    epochs=epochs
)

# Evaluate final model accuracy on test dataset
test_loss, test_acc = model.evaluate(test_generator)
print(f"Test Accuracy: {test_acc:.4f}")

import numpy as np
from sklearn.metrics import classification_report, accuracy_score

# Reset the test generator to ensure order is correct
test_generator.reset()

# Predict probabilities
predictions = model.predict(test_generator)
# Convert probabilities to binary class predictions (0 or 1)
y_pred = (predictions > 0.5).astype(int).flatten()

# Get true labels from the generator
y_true = test_generator.classes

# Get class label names
class_labels = list(test_generator.class_indices.keys())

# Calculate and print overall accuracy
acc = accuracy_score(y_true, y_pred)
print(f"Overall Test Accuracy: {acc * 100:.2f}%")

# Print classification report
print("\n--- Classification Report ---")
print(classification_report(y_true, y_pred, target_names=class_labels))

# Save the model in Keras native format
model.save('skin_cancer_cnn_model.keras')
print("Model saved locally as 'skin_cancer_cnn_model.keras'")

